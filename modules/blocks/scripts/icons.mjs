// Builds resources/icons/phosphor.php (server rendering) and resources/icons/phosphor.json
// (the builder's icon picker) from @iconify-json/ph: regular, bold, fill and light weights.
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'

const require = createRequire(import.meta.url)
const set = require('@iconify-json/ph/icons.json')
const WEIGHTS = ['bold', 'fill', 'light', 'thin', 'duotone']
const keep = (name) => !WEIGHTS.some((w) => name.endsWith('-' + w)) || ['bold', 'fill', 'light'].some((w) => name.endsWith('-' + w))

const icons = {}
for (const [name, data] of Object.entries(set.icons)) if (keep(name)) icons[name] = data.body
for (const [name, alias] of Object.entries(set.aliases ?? {})) if (keep(name) && set.icons[alias.parent]) icons[name] = set.icons[alias.parent].body

const names = Object.keys(icons).sort()
const php = (s) => "'" + s.replace(/\\/g, '\\\\').replace(/'/g, "\\'") + "'"
writeFileSync(
  new URL('../resources/icons/phosphor.php', import.meta.url),
  '<?php\n\n// Generated by scripts/icons.mjs from @iconify-json/ph (MIT) — do not edit.\nreturn [\n' + names.map((n) => `    ${php(n)} => ${php(icons[n])},`).join('\n') + '\n];\n',
)
writeFileSync(new URL('../resources/icons/phosphor.json', import.meta.url), JSON.stringify(names.filter((n) => !/-(bold|fill|light)$/.test(n))))
console.log(`icons: ${names.length} written (${set.width ?? 256}px grid)`)

