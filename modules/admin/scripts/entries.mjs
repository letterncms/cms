// Generates import-map entry modules for CommonJS packages (react, react-dom…).
// Bundlers cannot see CJS named exports through `export *`, so they are listed explicitly.
import { writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'

const require = createRequire(import.meta.url)
const cjs = {
  react: 'react',
  'jsx-runtime': 'react/jsx-runtime',
  'react-dom': 'react-dom',
  'react-dom-client': 'react-dom/client',
}

for (const [file, specifier] of Object.entries(cjs)) {
  const names = Object.keys(require(specifier)).filter((n) => /^[A-Za-z_$][\w$]*$/.test(n) && n !== 'default')
  const body = [
    `// Generated by scripts/entries.mjs — do not edit.`,
    `import * as mod from '${specifier}'`,
    `const m: any = (mod as any).default ?? mod`,
    `export default m`,
    `export const { ${names.join(', ')} } = m`,
    '',
  ].join('\n')
  writeFileSync(new URL(`../src/entries/${file}.ts`, import.meta.url), body)
}
console.log('entries: generated')
