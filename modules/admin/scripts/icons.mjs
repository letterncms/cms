// Builds src/lib/icon-data.ts from src/icons.json using locally installed @iconify-json/* sets.
// Icons are bundled offline: no CDN, no runtime fetch, CSP-friendly.
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'

const require = createRequire(import.meta.url)
const map = JSON.parse(readFileSync(new URL('../src/icons.json', import.meta.url), 'utf8'))
const sets = new Map()
const out = {}
const missing = []

for (const [name, id] of Object.entries(map)) {
  if (name.startsWith('$')) continue
  const [prefix, icon] = id.split(':')
  if (!sets.has(prefix)) sets.set(prefix, require(`@iconify-json/${prefix}/icons.json`))
  const set = sets.get(prefix)
  let data = set.icons[icon]
  let key = icon
  for (let i = 0; !data && set.aliases?.[key] && i < 5; i++) {
    key = set.aliases[key].parent
    data = set.icons[key]
  }
  if (!data) {
    missing.push(id)
    continue
  }
  out[name] = [data.body, data.width ?? set.width ?? 16, data.height ?? set.height ?? 16]
}

if (missing.length) {
  console.error('Missing icons:', missing.join(', '))
  process.exit(1)
}

// The whole set for the icon picker and any icon named by its Phosphor name: loaded on demand, never with the app.
const ph = require('@iconify-json/ph/icons.json')
const catalog = {}
for (const [name, data] of Object.entries(ph.icons)) {
  if (/-(bold|fill|thin|light|duotone)$/.test(name)) continue
  if ((data.width ?? ph.width) !== 256 || (data.height ?? ph.height) !== 256) throw new Error(`Unexpected size for ph:${name}`)
  catalog[name] = data.body
}
// What each icon is also known by, from Phosphor's own keywords, so "email" finds the envelope.
const { icons: meta } = await import('@phosphor-icons/core')
const tags = Object.fromEntries(meta.filter((i) => catalog[i.name]).map((i) => [i.name, [...new Set([...i.tags, ...i.categories])].join(' ')]).filter(([, words]) => words))
const semantic = Object.fromEntries(Object.entries(map).filter(([name, id]) => !name.startsWith('$') && id.startsWith('ph:')).map(([name, id]) => [name, id.slice(3)]))
writeFileSync(new URL('../src/lib/icon-catalog.json', import.meta.url), JSON.stringify({ icons: catalog, tags, semantic }) + '\n')
console.log(`icon catalog: ${Object.keys(catalog).length} written`)

writeFileSync(
  new URL('../src/lib/icon-data.ts', import.meta.url),
  '// Generated by scripts/icons.mjs — do not edit.\nexport const ICONS: Record<string, [body: string, width: number, height: number]> = ' + JSON.stringify(out) + '\n',
)
console.log(`icons: ${Object.keys(out).length} written`)
